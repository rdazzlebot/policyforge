@pytest.fixture
def project(tmp_path, monkeypatch):
    import policyforge.cli as cli_mod

    monkeypatch.setattr(cli_mod, "load_config", lambda: {})
    monkeypatch.setattr("policyforge.frameworks.registry.is_ignored", lambda path: True)
    (tmp_path / "local_content").mkdir()
    (tmp_path / "local_content" / "criteria.txt").write_text(SYNTHETIC_CRITERIA, encoding="utf-8")
    _synthetic_mapping(
        tmp_path / "local_content" / "mapping.xlsx", [("CC1.1", "x", "AC-02, AC-3(1)")]
    )
    monkeypatch.chdir(tmp_path)
    return tmp_path


def _run(*args):
    from policyforge import cli as cli_mod

    return CliRunner().invoke(cli_mod.cli, ["etl-soc2-tsc", *args])


def test_the_etl_writes_a_licensed_catalog_and_its_manifest(project):
    import yaml

    out = project / "local_content" / "soc2-tsc" / "controls.json"
    result = _run(
        "--criteria",
        "local_content/criteria.txt",
        "--mapping",
        "local_content/mapping.xlsx",
        "--nist-comparison",
        str(WORKBOOK),
        "--out",
        str(out),
    )
    assert result.exit_code == 0, result.output
    rows = json.loads(out.read_text(encoding="utf-8"))
    assert [r["control_id"] for r in rows] == ["CC1.1", "CC1.2", "CC2.1", "A1.1"]
    assert rows[0]["source_crosswalk"] == {"nist-800-53": "AC-2"}
    manifest = yaml.safe_load((out.parent / "framework.yaml").read_text(encoding="utf-8"))
    assert manifest["licence"] == "licensed"
    assert manifest["framework_id"] == "aicpa-tsc"
    assert manifest["crosswalk_relationship"] == "source-untyped"
    assert manifest["crosswalk_source"] == soc2_tsc.CROSSWALK_SOURCE
    assert manifest["crosswalk_changed_since_rev4"] == {"AC-2": nist_rev4_rev5.CHANGED}
    assert manifest["crosswalk_refused"] == [
        {"criterion": "CC1.1", "target": "AC-3(1)", "reason": nist_rev4_rev5.WITHDRAWN}
    ]
    assert "not mapped by the source: CC1.2, CC2.1, A1.1" in result.output


def test_the_etl_refuses_a_destination_outside_the_boundary_and_writes_nothing(project):
    out = project / "output" / "tsc" / "controls.json"
    result = _run("--criteria", "local_content/criteria.txt", "--out", str(out), "--force")
    assert result.exit_code != 0
    assert "would be read as organization-internal" in result.output
    assert not out.exists()


def test_a_refused_parse_writes_nothing(project):
    (project / "local_content" / "criteria.txt").write_text(
        SYNTHETIC_CRITERIA.replace("CC1.2 ", "CC1.3 "), encoding="utf-8"
    )
    out = project / "local_content" / "soc2-tsc" / "controls.json"
    result = _run("--criteria", "local_content/criteria.txt", "--out", str(out))
    assert result.exit_code != 0
    assert "Nothing was written" in result.output
    assert not out.exists() and not (out.parent / "framework.yaml").exists()


def test_by_default_the_catalog_reaches_only_local_models(project):
    """The DEFAULT half of 80's amended rule (#410): with no boundary
    declaration, TSC content goes to local models only. The declared-widening
    half waits on 80's ruling on #459 about which declaration is real."""
    from policyforge.llm import boundary

    out = project / "local_content" / "soc2-tsc" / "controls.json"
    assert _run("--criteria", "local_content/criteria.txt", "--out", str(out)).exit_code == 0
    path = Path("local_content/soc2-tsc/controls.json")
    assert boundary.classify_path(path, {}).klass == boundary.LICENSED
    with pytest.raises(boundary.BoundaryViolation):
        boundary.enforce(path, {"llm": {"provider": "anthropic", "model": "any"}})
    local = {"llm": {"provider": "openai-compat", "base_url": "http://127.0.0.1:11434/v1"}}
    assert boundary.enforce(path, local).allowed


def test_coverage_reads_the_mapping_as_partial_and_names_its_source(project):
    """Through #408's declared-relationship and #449's source name, read from
    the user's own manifest: a TSC criterion is never counted fully covered on
    the AICPA's untyped link, and /coverage says whose mapping it is."""
    from policyforge.crosswalk.overlay import relationships_for
    from policyforge.frameworks.registry import (
        declared_crosswalk_relationships,
        declared_crosswalk_sources,
    )
    from policyforge.ingest.schema import load_controls

    out = project / "local_content" / "soc2-tsc" / "controls.json"
    assert (
        _run(
            "--criteria",
            "local_content/criteria.txt",
            "--mapping",
            "local_content/mapping.xlsx",
            "--nist-comparison",
            str(WORKBOOK),
            "--out",
            str(out),
        ).exit_code
        == 0
    )
    roots = [project / "local_content"]
    declared = declared_crosswalk_relationships(roots=roots)
    assert declared.get("aicpa-tsc") == "source-untyped"
    assert declared_crosswalk_sources(roots=roots).get("aicpa-tsc") == soc2_tsc.CROSSWALK_SOURCE
    controls = load_controls(out)
    table = relationships_for(controls, [], declared=declared)
    assert table == {("aicpa-tsc", "CC1.1", "AC-2"): "source-untyped"}
